# Оригінальний текст
text = "Програмування відкриває нові можливості для навчання та розв'язання складних завдань."

# Перетворюємо текст у верхній регістр
uppercase_text = text.upper()
print("Текст у верхньому регістрі:", uppercase_text)

# Замінюємо слово "навчання" на "розвиток"
mod_text = text.replace("навчання", "розвиток")
print("Змінений текст:", mod_text)

# Підраховуємо кількість символів у тексті
length = len(text)
print("Кількість символів у тексті:", length)

